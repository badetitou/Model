//! Generator: FM3 export + `traits.json` -> `src/generated.rs`.
//! Shared by `examples/generate.rs` (writes) and `tests/generated.rs` (checks).

use std::collections::BTreeSet;
use std::fmt::Write;

use model_fm3::{Id, Metamodel, Ref};

fn str_list(v: &serde_json::Value, key: &str) -> Vec<String> {
    v.get(key)
        .and_then(|x| x.as_array())
        .map(|a| {
            a.iter()
                .filter_map(|s| s.as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

fn ref_name(mm: &Metamodel, r: &Ref) -> String {
    match r {
        Ref::Builtin(n) => n.clone(),
        Ref::Id(id) => mm
            .class(*id)
            .map(|c| c.name.clone())
            .or_else(|| mm.trait_(*id).map(|t| t.name.clone()))
            .unwrap_or_else(|| id.to_string()),
    }
}

fn list(items: &[String]) -> String {
    let v: Vec<String> = items.iter().map(|s| format!("{s:?}")).collect();
    format!("&[{}]", v.join(", "))
}

/// FM3 traits used by `owner`, transitively, plus itself.
fn closure(mm: &Metamodel, owner: Id, out: &mut BTreeSet<String>) {
    let (name, uses): (String, Vec<Id>) = match (mm.class(owner), mm.trait_(owner)) {
        (Some(c), _) => (c.name.clone(), c.traits.clone()),
        (_, Some(t)) => (t.name.clone(), t.traits.clone()),
        _ => return,
    };
    if mm.trait_(owner).is_some() && !out.insert(name) {
        return;
    }
    for u in uses {
        closure(mm, u, out);
    }
}

pub fn generate(mm: &Metamodel, config: &serde_json::Value) -> Result<String, String> {
    let defs = config
        .get("traits")
        .and_then(|t| t.as_array())
        .ok_or("traits.json: missing `traits` array")?;
    if defs.len() > 64 {
        return Err("at most 64 traits fit in a TraitMask".into());
    }
    let mut out = String::from(
        "// @generated by `cargo run -p model-traits --example generate`; do not edit.\n\
         // Sources: traits.json + the FM3 JSON export of FamixJava.\n\n\
         use crate::schema::{ClassTraits, ContainmentDef, PropDef, PropType, RelationDef, TraitDef};\n\n\
         pub static TRAITS: &[TraitDef] = &[\n",
    );
    let mut names = Vec::new();
    let mut fm3_of: Vec<Vec<String>> = Vec::new();
    for (bit, d) in defs.iter().enumerate() {
        let name = d["name"].as_str().ok_or("trait without name")?.to_string();
        let fm3 = str_list(d, "fm3");
        let carries = str_list(d, "carries");
        let (mut props, mut rels, mut contains) = (Vec::new(), Vec::new(), Vec::new());
        for t in &fm3 {
            let ft = mm
                .trait_by_name(t)
                .ok_or_else(|| format!("{name}: FM3 trait `{t}` not in the export"))?;
            for p in mm.properties_of(ft.id) {
                let multi = p.multivalued;
                let opposite = p.opposite.and_then(|o| mm.property(o));
                match &p.type_ref {
                    Ref::Builtin(b) if !p.derived => {
                        let ty = match b.as_str() {
                            "String" => "String",
                            "Number" => "Number",
                            "Boolean" => "Boolean",
                            other => return Err(format!("{name}.{}: type `{other}`", p.name)),
                        };
                        props.push(format!(
                            "PropDef {{ name: {:?}, ty: PropType::{ty}, multivalued: {multi} }}",
                            p.name
                        ));
                    }
                    Ref::Builtin(_) => {} // derived metric: computed, not stored
                    r @ Ref::Id(_) => {
                        let target = ref_name(mm, r);
                        if multi && opposite.is_some_and(|o| o.container) {
                            contains.push(format!(
                                "ContainmentDef {{ via: {:?}, target: {target:?} }}",
                                p.name
                            ));
                        }
                        rels.push(format!(
                            "RelationDef {{ name: {:?}, target: {target:?}, multivalued: {multi}, \
                             derived: {}, opposite: {} }}",
                            p.name,
                            p.derived,
                            opposite.map_or("None".into(), |o| format!("Some({:?})", o.name)),
                        ));
                    }
                }
            }
        }
        let block = |items: &[String]| {
            if items.is_empty() {
                "&[]".to_string()
            } else {
                format!(
                    "&[\n            {},\n        ]",
                    items.join(",\n            ")
                )
            }
        };
        let _ = write!(
            out,
            "    TraitDef {{\n        name: {name:?},\n        bit: {bit},\n        fm3: {},\n        \
             props: {},\n        relations: {},\n        carries: {},\n        contains: {},\n    }},\n",
            list(&fm3),
            block(&props),
            block(&rels),
            list(&carries),
            block(&contains),
        );
        names.push(name);
        fm3_of.push(fm3);
    }
    out.push_str("];\n\npub static CLASS_TRAITS: &[ClassTraits] = &[\n");
    for c in &mm.classes {
        let mut used = BTreeSet::new();
        let mut cur = Some(c.id);
        let mut seen = BTreeSet::new();
        while let Some(id) = cur.filter(|i| seen.insert(*i)) {
            closure(mm, id, &mut used);
            cur = mm
                .class(id)
                .and_then(|k| k.superclass.as_ref())
                .and_then(Ref::id);
        }
        let ours: Vec<String> = names
            .iter()
            .zip(&fm3_of)
            .filter(|(_, f)| f.iter().any(|t| used.contains(t)))
            .map(|(n, _)| n.clone())
            .collect();
        if ours.is_empty() {
            continue;
        }
        let pkg = c
            .package
            .and_then(|p| mm.package(p))
            .map_or(String::new(), |p| format!("{}.", p.name));
        let _ = writeln!(
            out,
            "    ClassTraits {{ fm3_class: {:?}, traits: {} }},",
            format!("{pkg}{}", c.name),
            list(&ours)
        );
    }
    out.push_str("];\n");
    Ok(out)
}
